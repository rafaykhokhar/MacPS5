fn write(path: impl AsRef<Path>, text: impl AsRef<[u8]>) -> Result<()> {
    fs::write(path, text).map_err(|e| e.to_string())
}
fn run(command: &mut Command) -> Result<String> {
    let output = command.output().map_err(|e| format!("{command:?}: {e}"))?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    let stderr = String::from_utf8_lossy(&output.stderr);
    print!("{stdout}");
    eprint!("{stderr}");
    if !output.status.success() {
        return Err(format!("{command:?} failed: {}", output.status));
    }
    Ok(format!("{stdout}{stderr}"))
}
struct Fixture {
    assembly: String,
    header: String,
    entries: Vec<String>,
}
impl Fixture {
    fn new(declarations: &str) -> Self {
        Self {
            assembly: String::new(),
            header: format!(
                "// Generated by Rust\n#pragma once\n#include \"guest_cpu.hpp\"\n{declarations}\n"
            ),
            entries: vec![],
        }
    }
    fn add(&mut self, name: &str, mut code: Vec<u8>, fields: impl AsRef<str>) -> Result<()> {
        code.push(0xc3);
        self.assembly
            .push_str(&aot::translate(&code, 0, name, false, false)?.0);
        self.header.push_str(&format!(
            "extern \"C\" void {name}(NativePS5::GuestCpu*);\n"
        ));
        self.entries.push(format!("{{{name},{}}}", fields.as_ref()));
        Ok(())
    }
    fn array(&mut self, type_name: &str, name: &str) {
        self.header.push_str(&format!(
            "inline const {type_name} {name}[]={{ {} }};\n",
            self.entries.join(",")
        ));
        self.entries.clear();
    }
    fn save(&self, build: &Path, name: &str) -> Result<PathBuf> {
        let asm = build.join(format!("{name}-fixtures.S"));
        write(&asm, &self.assembly)?;
        write(build.join(format!("{name}-fixtures.hpp")), &self.header)?;
        Ok(asm)
    }
}
fn hex(s: &str) -> Vec<u8> {
    s.split_whitespace()
        .map(|b| u8::from_str_radix(b, 16).expect("fixed fixture hex"))
        .collect()
}
fn vex(dst: u8, src: u8, map: u8) -> u8 {
    (if dst < 8 { 128 } else { 0 }) | 64 | (if src < 8 { 32 } else { 0 }) | map
}
fn compile(
    source: &Path,
    build: &Path,
    name: &str,
    files: &[PathBuf],
    elf: Option<&Path>,
) -> Result<String> {
    let binary = build.join(name);
    let runtime = std::env::current_exe()
        .map_err(|e| e.to_string())?
        .parent()
        .ok_or("Missing binary directory")?
        .join("libnative_ps5.a");
    if !runtime.is_file() {
        return Err("Rust runtime archive is missing; run cargo build before native checks".into());
    }
    let mut command = Command::new("xcrun");
    command
        .args([
            "clang++",
            "-arch",
            "arm64",
            "-std=c++20",
            "-O2",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-DNATIVE_PS5_RUST_PAYLOAD=1",
            "-DNATIVE_PS5_RUST_LOADER=1",
            "-I",
        ])
        .arg(build)
        .arg("-I")
        .arg(source)
        .args(files)
        .arg(runtime)
        .args(crate::module_compiler::RUNTIME_LINK_ARGS)
        .arg("-o")
        .arg(&binary);
    run(&mut command)?;
    let mut command = Command::new(binary);
    if let Some(elf) = elf {
        command.arg(elf);
    }
    run(&mut command)
}
fn verify_fixture(source: &Path, build: &Path, name: &str, f: &Fixture) -> Result<()> {
    println!("Checking Rust-generated {name} instructions");
    let asm = f.save(build, name)?;
    compile(
        source,
        build,
        &format!("{name}-verify"),
        &[
            source.join("guest_cpu.cpp"),
            source.join(format!("{}_verify.cpp", name.replace('-', "_"))),
            asm,
        ],
        None,
    )?;
    Ok(())
}
fn bmi(source: &Path, build: &Path) -> Result<()> {
    let mut f = Fixture::new(
        "struct MulxFixture { void (*block)(NativePS5::GuestCpu*); unsigned bits,high,low,source; bool memory; };",
    );
    for bits in [32, 64] {
        for (high, low, src, mem) in [
            (0u8, 1u8, 3u8, false),
            (0, 0, 0, false),
            (2, 1, 3, false),
            (0, 2, 3, false),
            (2, 2, 2, false),
            (3, 1, 3, false),
            (0, 3, 3, false),
            (9, 10, 8, false),
            (0, 1, 3, true),
            (3, 3, 3, true),
            (9, 10, 8, true),
        ] {
            let name = format!("mulx_{bits}_{high}_{low}_{src}_{}", u8::from(mem));
            f.add(
                &name,
                vec![
                    0xc4,
                    vex(high, src, 2),
                    (if bits == 64 { 128 } else { 0 }) | ((!low & 15) << 3) | 3,
                    0xf6,
                    (if mem { 0 } else { 0xc0 }) | ((high & 7) << 3) | (src & 7),
                ],
                format!("{bits},{high},{low},{src},{mem}"),
            )?;
        }
    }
    f.array("MulxFixture", "mulxFixtures");
    verify_fixture(source, build, "mulx", &f)?;
    let mut f = Fixture::new(
        "struct AndnFixture { void (*block)(NativePS5::GuestCpu*); unsigned bits,destination,first,second; bool memory; };",
    );
    for bits in [32, 64] {
        for (dst, first, second, mem) in [
            (0u8, 1u8, 2u8, false),
            (1, 1, 2, false),
            (2, 1, 2, false),
            (9, 10, 8, false),
            (0, 1, 2, true),
            (2, 1, 2, true),
        ] {
            f.add(
                &format!("andn_{bits}_{dst}_{first}_{second}_{}", u8::from(mem)),
                vec![
                    0xc4,
                    vex(dst, second, 2),
                    (if bits == 64 { 128 } else { 0 }) | ((!first & 15) << 3),
                    0xf2,
                    (if mem { 0 } else { 0xc0 }) | ((dst & 7) << 3) | (second & 7),
                ],
                format!("{bits},{dst},{first},{second},{mem}"),
            )?;
        }
    }
    f.array("AndnFixture", "andnFixtures");
    verify_fixture(source, build, "andn", &f)?;
    let mut f = Fixture::new(
        "struct RorxFixture { void (*block)(NativePS5::GuestCpu*); unsigned bits,destination,source,count; bool memory; };",
    );
    for bits in [32, 64] {
        for (dst, src, mem) in [
            (0u8, 1u8, false),
            (1, 1, false),
            (9, 10, false),
            (0, 1, true),
            (1, 1, true),
        ] {
            for count in 0..=255u8 {
                f.add(
                    &format!("rorx_{bits}_{dst}_{src}_{}_{count}", u8::from(mem)),
                    vec![
                        0xc4,
                        vex(dst, src, 3),
                        if bits == 64 { 0xfb } else { 0x7b },
                        0xf0,
                        (if mem { 0 } else { 0xc0 }) | ((dst & 7) << 3) | (src & 7),
                        count,
                    ],
                    format!("{bits},{dst},{src},{count},{mem}"),
                )?;
            }
        }
    }
    f.array("RorxFixture", "rorxFixtures");
    verify_fixture(source, build, "rorx", &f)?;
    let mut f = Fixture::new("");
    for (name, bytes) in [
        ("bextr32", "c4 e2 70 f7 c2"),
        ("bextr64", "c4 e2 f0 f7 c2"),
        ("bextr_alias", "c4 e2 70 f7 c0"),
        ("bextr_control_alias", "c4 e2 f8 f7 c2"),
        ("bextr_high", "c4 42 b0 f7 c7"),
        ("bextr_memory", "c4 e2 f0 f7 02"),
    ] {
        f.add(name, hex(bytes), "")?;
    }
    verify_fixture(source, build, "bextr", &f)?;
    let mut f = Fixture::new(
        "struct MovbeFixture { void (*block)(NativePS5::GuestCpu*); unsigned bits; bool store; };",
    );
    for bits in [16, 32, 64] {
        for store in [false, true] {
            let mut bytes = match bits {
                16 => vec![0x66],
                64 => vec![0x48],
                _ => vec![],
            };
            bytes.extend([0x0f, 0x38, if store { 0xf1 } else { 0xf0 }, 1]);
            f.add(
                &format!("movbe_{bits}_{}", u8::from(store)),
                bytes,
                format!("{bits},{store}"),
            )?;
        }
    }
    f.array("MovbeFixture", "movbeFixtures");
    verify_fixture(source, build, "movbe", &f)
}
fn vectors(source: &Path, build: &Path) -> Result<()> {
    let mut f = Fixture::new(
        "struct VectorXorFixture { void (*block)(NativePS5::GuestCpu*); unsigned destination,first,second,size; bool memory; };",
    );
    for bits in [128, 256] {
        for pp in [0, 1] {
            for (dst, first, second, mem) in [
                (0u8, 1u8, 2u8, false),
                (1, 1, 2, false),
                (2, 1, 2, false),
                (8, 10, 9, false),
                (7, 7, 7, false),
                (0, 1, 0, true),
                (1, 1, 0, true),
            ] {
                f.add(
                    &format!(
                        "vector_xor_{bits}_{pp}_{dst}_{first}_{second}_{}",
                        u8::from(mem)
                    ),
                    vec![
                        0xc4,
                        vex(dst, second, 1),
                        ((!first & 15) << 3) | (if bits == 256 { 4 } else { 0 }) | pp,
                        0x57,
                        (if mem { 0 } else { 0xc0 }) | ((dst & 7) << 3) | (second & 7),
                    ],
                    format!("{dst},{first},{second},{},{mem}", bits / 8),
                )?;
            }
        }
    }
    f.array("VectorXorFixture", "vectorXorFixtures");
    verify_fixture(source, build, "vector-xor", &f)?;
    let mut f = Fixture::new("");
    for (name, bytes) in [
        ("vector_load128", "c5 f8 10 00"),
        ("vector_store128", "c5 f8 11 00"),
        ("vector_aligned_load128", "c5 f8 28 00"),
        ("vector_aligned_store128", "c5 f8 29 00"),
        ("vector_load256", "c5 fc 10 00"),
        ("vector_store256", "c5 fc 11 00"),
        ("vector_aligned_load256", "c5 fc 28 00"),
        ("vector_aligned_store256", "c5 fc 29 00"),
        ("vector_reg128", "c5 78 10 c1"),
        ("vector_regstore128", "c5 78 11 c1"),
        ("vector_reg256", "c4 41 7c 10 c1"),
        ("vector_self128", "c5 f8 10 c0"),
        ("vector_sib256", "c4 41 7c 10 7c 8a 10"),
        ("vector_rip128", "c5 f8 10 05 10 00 00 00"),
    ] {
        f.add(name, hex(bytes), "")?;
    }
    verify_fixture(source, build, "vector", &f)
}
fn shifts(source: &Path, build: &Path) -> Result<()> {
    let mut f = Fixture::new(
        "struct ShiftFixture { void(*block)(NativePS5::GuestCpu*); unsigned bits,operation; int count; };",
    );
    for bits in [32, 64] {
        for (operation, group) in [4, 5, 7, 0, 1].iter().enumerate() {
            for count in [-1, 0, 1, 31, 32, 63, 64, 255, 256] {
                let mut bytes = if bits == 64 { vec![0x48] } else { vec![] };
                bytes.extend([
                    if count == -1 {
                        0xd3
                    } else if count == 256 {
                        0xd1
                    } else {
                        0xc1
                    },
                    0xc0 | (group << 3),
                ]);
                if (0..256).contains(&count) {
                    bytes.push(count as u8);
                }
                let suffix = if count == -1 {
                    "cl".to_owned()
                } else if count == 256 {
                    "one".to_owned()
                } else {
                    count.to_string()
                };
                f.add(
                    &format!("shift_{bits}_{operation}_{suffix}"),
                    bytes,
                    format!(
                        "{bits},{operation},{}",
                        if count == 256 { 1 } else { count }
                    ),
                )?;
            }
        }
    }
    f.array("ShiftFixture", "shiftFixtures");
    for (name, bytes) in [
        ("shift_alias", "48 d3 e1"),
        ("shift_high", "49 d3 cb"),
        ("shift_memory", "48 d3 3a"),
    ] {
        f.add(name, hex(bytes), "")?;
    }
    verify_fixture(source, build, "shift", &f)
}
fn conditional(source: &Path, build: &Path) -> Result<()> {
    let mut f = Fixture::new(
        "using ConditionalBlock=void(*)(NativePS5::GuestCpu*);\nstruct ConditionalMove { ConditionalBlock block; unsigned condition,bits,destination,source; bool memory; };\nstruct ConditionalByte { ConditionalBlock block; unsigned condition,destination,bit; bool memory; };",
    );
    for condition in 0..16 {
        for bits in [32, 64] {
            for (variant, modrm, dst, src, memory) in [
                (0, 0xc1, 0, 1, false),
                (1, 2, 0, 0, true),
                (2, 0xc7, 8, 15, false),
                (3, 0xc0, 0, 0, false),
            ] {
                let rex = (if bits == 64 { 0x48 } else { 0x40 }) | if variant == 2 { 5 } else { 0 };
                f.add(
                    &format!("cmov_{condition}_{bits}_{variant}"),
                    vec![rex, 0x0f, 0x40 + condition, modrm],
                    format!("{condition},{bits},{dst},{src},{memory}"),
                )?;
            }
        }
    }
    f.array("ConditionalMove", "conditionalMoves");
    for condition in 0..16 {
        for (variant, prefix, modrm, dst, bit, memory) in [
            (0, 0, 0xc0, 0, 0, false),
            (1, 0, 0xc4, 0, 8, false),
            (2, 0x40, 0xc4, 4, 0, false),
            (3, 0x41, 0xc7, 15, 0, false),
            (4, 0, 2, 0, 0, true),
            (5, 0, 0xfc, 0, 8, false),
            (6, 0x44, 0xf8, 0, 0, false),
        ] {
            let mut bytes = if prefix == 0 { vec![] } else { vec![prefix] };
            bytes.extend([0x0f, 0x90 + condition, modrm]);
            f.add(
                &format!("setcc_{condition}_{variant}"),
                bytes,
                format!("{condition},{dst},{bit},{memory}"),
            )?;
        }
    }
    f.array("ConditionalByte", "conditionalBytes");
    verify_fixture(source, build, "conditional", &f)
}
fn accumulators(source: &Path, build: &Path) -> Result<()> {
    let mut f = Fixture::new(
        "struct AccumulatorFixture { void (*block)(NativePS5::GuestCpu*); unsigned bits,operation; uint64_t immediate; };",
    );
    for bits in [8, 32, 64] {
        for (operation, opcode) in [4, 0x2c, 0x3c].iter().enumerate() {
            let values: Vec<u32> = if bits == 8 {
                (0..256).collect()
            } else {
                vec![0, 1, 15, 0x7fffffff, 0x80000000, 0xffffffff]
            };
            for value in values {
                let mut bytes = if bits == 64 { vec![0x48] } else { vec![] };
                bytes.push(opcode + u8::from(bits != 8));
                bytes.extend_from_slice(&value.to_le_bytes()[..if bits == 8 { 1 } else { 4 }]);
                let immediate = if bits == 64 {
                    value as i32 as i64 as u64
                } else {
                    value as u64
                };
                f.add(
                    &format!("accumulator_{bits}_{operation}_{value}"),
                    bytes,
                    format!("{bits},{operation},{immediate}ull"),
                )?;
            }
        }
    }
    f.array("AccumulatorFixture", "accumulatorFixtures");
    verify_fixture(source, build, "accumulator", &f)
}

/// Run the Rust-generated native arithmetic oracle without the full homebrew suite.
pub fn arithmetic_native(build: &Path) -> Result<()> {
    if !cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        return Err("Native checks require ARM64 macOS".into());
    }
    fs::create_dir_all(build).map_err(|e| e.to_string())?;
    let source = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("Missing source directory")?;
    negate_borrow(source, build)
}

/// Execute Rust-generated Metal shaders on the actual unified-memory Apple GPU.
pub fn gpu_native(build: &Path) -> Result<()> {
    if !cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        return Err("GPU checks require Apple Silicon macOS".into());
    }
    fs::create_dir_all(build).map_err(|e| e.to_string())?;
    let source = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("Missing source directory")?;
    native_driver(source, build, "rdna_metal", &[], None)?;
    native_driver(source, build, "rdna_render", &[], None)?;
    native_driver(source, build, "graphics_submission", &[], None)
}

pub fn native(build: &Path, homebrew: &Path) -> Result<()> {
    native_with(build, homebrew, true)
}
pub fn payload_native(build: &Path, homebrew: &Path) -> Result<()> {
    native_with(build, homebrew, false)
}
fn native_with(build: &Path, homebrew: &Path, cpu_tests: bool) -> Result<()> {
    if !cfg!(all(target_os = "macos", target_arch = "aarch64")) {
        return Err("Native checks require ARM64 macOS".into());
    }
    let file = fs::read(homebrew).map_err(|e| e.to_string())?;
    if format!("{:x}", Sha256::digest(&file))
        != "308fbb17946974f0c2e888988d4f16f98681ea91a8a957a314b3518e5e45a567"
    {
        return Err(
            "Native homebrew harness requires the checked Crispy Doom ELF; SHA-256 differs".into(),
        );
    }
    let elf = Elf::parse(&file)?;
    fs::create_dir_all(build).map_err(|e| e.to_string())?;
    let source = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("Missing source directory")?;
    gpu_native(build)?;
    native_driver(
        source,
        build,
        "strings",
        &[
            "guest_cpu.cpp",
            "bootstrap_services.cpp",
            "rust/legacy_abi.cpp",
        ],
        None,
    )?;
    module_lifecycle(source, build)?;
    native_driver(source, build, "entry", &[], Some(homebrew))?;
    import_registry(source, build)?;
    let sce_fixture = build.join("rust-sce-import.elf");
    write(&sce_fixture, crate::loader_fixture::graphics(true))?;
    compile(
        source,
        build,
        "rust-sce-loader-verify",
        &[
            source.join("elf_image.cpp"),
            source.join("sce_loader_verify.cpp"),
        ],
        Some(&sce_fixture),
    )?;
    native_driver(
        source,
        build,
        "loader",
        &["elf_image.cpp", "rust/loader_abi.cpp"],
        Some(homebrew),
    )?;
    compile(
        source,
        build,
        "rust-loader-runtime-verify",
        &[
            source.join("elf_image.cpp"),
            source.join("loader_verify.cpp"),
        ],
        Some(homebrew),
    )?;
    compile(
        source,
        build,
        "format-verify",
        &[
            source.join("guest_cpu.cpp"),
            source.join("bootstrap_services.cpp"),
            source.join("format_verify.cpp"),
        ],
        None,
    )?;
    if cpu_tests {
        negate_borrow(source, build)?;
        bytes(source, build)?;
        logical(source, build)?;
        bmi(source, build)?;
        vectors(source, build)?;
        shifts(source, build)?;
        conditional(source, build)?;
        accumulators(source, build)?;
        let start = build.join("startup.S");
        let crt = build.join("crt.S");
        write(
            &start,
            aot::translate(
                elf.code(elf.entry, 4096)?,
                elf.entry,
                "translated_start",
                false,
                false,
            )?
            .0,
        )?;
        write(
            &crt,
            aot::translate(
                elf.code(0x3a0, 4096)?,
                0x3a0,
                "translated_crt",
                false,
                false,
            )?
            .0,
        )?;
        compile(
            source,
            build,
            "startup-verify",
            &[
                source.join("guest_cpu.cpp"),
                source.join("elf_image.cpp"),
                source.join("startup_verify.cpp"),
                start,
                crt,
            ],
            Some(homebrew),
        )?;
    }
    let kernel_artifacts = Discovery::run(
        &elf,
        BTreeSet::from([0x2ad0, 0x2ca0, 0x30e0, 0x3320, 0x3810]),
        20_000,
    )?
    .emit(&elf, &file, "kernel_copy")?;
    let kernel_assembly = build.join("kernel-copy.S");
    write(&kernel_assembly, kernel_artifacts.assembly)?;
    write(build.join("kernel-copy.hpp"), kernel_artifacts.header)?;
    write(
        build.join("kernel-copy.json"),
        serde_json::to_vec_pretty(&kernel_artifacts.manifest).map_err(|e| e.to_string())?,
    )?;
    compile(
        source,
        build,
        "kernel-copy-verify",
        &[
            source.join("guest_cpu.cpp"),
            source.join("elf_image.cpp"),
            source.join("bootstrap_services.cpp"),
            source.join("dispatcher.cpp"),
            source.join("kernel_copy_verify.cpp"),
            kernel_assembly,
        ],
        Some(homebrew),
    )?;
    let artifacts = Discovery::run(&elf, BTreeSet::from([elf.entry]), 65_536)?.emit_with_trace(
        &elf,
        &file,
        "discovered",
        &BTreeSet::from([
            0x7ede, 0x53f2, 0x5419, 0x5440, 0x5467, 0x548e, 0x54b5, 0x54dc, 0x54ff, 0x5522, 0x6b0a,
            0x6b2d, 0x5534, 0xf4,
        ]),
    )?;
    let assembly = build.join("discovered.S");
    write(&assembly, artifacts.assembly)?;
    write(build.join("discovered.hpp"), artifacts.header)?;
    write(
        build.join("discovered.json"),
        serde_json::to_vec_pretty(&artifacts.manifest).map_err(|e| e.to_string())?,
    )?;
    let result = compile(
        source,
        build,
        "payload-boot-verify",
        &[
            source.join("guest_cpu.cpp"),
            source.join("elf_image.cpp"),
            source.join("bootstrap_services.cpp"),
            source.join("dispatcher.cpp"),
            source.join("payload_boot_verify.cpp"),
            assembly,
        ],
        Some(homebrew),
    )?;
    // Rust payload records permit __patch_init to complete. Nine Rust libc
    // exports resolve before module initialization's missing load/start service. The selected-PC
    // checkpoints distinguish this path from earlier initialization failures.
    if !result.contains("NEXT: pc=397 fault=8 rax=268 reason=1;") {
        return Err("Homebrew migration boundary changed; investigate before accepting".into());
    }
    if !result.contains("GUEST pc=7ede rax=0 ")
        || !result.contains("GUEST pc=6b2d rax=0 ")
        || !result.contains("GUEST pc=5534 rax=ffffffff ")
        || !result.contains("GUEST pc=f4 rax=ffffffff ")
    {
        return Err(
            "Expected successful __patch_init and later unresolved sceKernelLoadStartModule were not observed".into(),
        );
    }
    let mut addresses = Vec::new();
    for pc in [
        0x53f2, 0x5419, 0x5440, 0x5467, 0x548e, 0x54b5, 0x54dc, 0x54ff, 0x5522,
    ] {
        let prefix = format!("GUEST pc={pc:x} rax=");
        let value = result
            .lines()
            .find_map(|line| line.strip_prefix(&prefix))
            .and_then(|line| line.split_whitespace().next())
            .ok_or("Missing string-resolution checkpoint")?;
        addresses.push(u64::from_str_radix(value, 16).map_err(|e| e.to_string())?);
    }
    if addresses[0] == 0
        || addresses
            .windows(2)
            .any(|pair| pair[0].checked_add(16) != Some(pair[1]))
    {
        return Err("Rust string exports did not resolve to their distinct thunk slots".into());
    }
    let dlsym = result
        .lines()
        .find_map(|line| line.strip_prefix("GUEST pc=6b0a rax="))
        .and_then(|line| line.split_whitespace().next())
        .ok_or("Missing kernel dlsym checkpoint")?;
    let dlsym = u64::from_str_radix(dlsym, 16).map_err(|e| e.to_string())?;
    if dlsym == 0 || dlsym.checked_add(96) != Some(addresses[0]) {
        return Err("Kernel dlsym did not resolve to the existing service".into());
    }
    println!(
        "PASS: real __patch_init succeeds; nine Rust libc exports and kernel dlsym resolve; __rtld_sprx_init reaches missing sceKernelLoadStartModule"
    );
    println!(
        "PASS: Rust translation and native verification completed. Retained C++ runtime used; gameplay not reached."
    );
    Ok(())
}

